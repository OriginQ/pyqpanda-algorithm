"""PyQPanda3 CPUQVM backend for BF-DCQO and the QAOA benchmark baseline."""
from __future__ import annotations

import math

import numpy as np


def available() -> bool:
    """Return ``True`` when ``pyqpanda3.core`` can be imported."""
    try:
        import pyqpanda3.core  # noqa: F401

        return True
    except Exception:
        return False


def _import_qpanda():
    try:
        from pyqpanda3.core import CNOT, H, CPUQVM, QCircuit, QProg, RX, RY, RZ, measure
    except ImportError as exc:
        raise ImportError(
            "PyQPanda3 backend requested but pyqpanda3 is not installed. "
            "Install pyqpanda3>=0.4.0."
        ) from exc
    return QCircuit, QProg, CPUQVM, H, RX, RY, RZ, CNOT, measure


def pauli_rotation_recipe(pauli_string, theta: float):
    """Return a gate recipe for ``exp(-i theta P)``.

    The decomposition uses basis changes, a CNOT parity ladder, one ``RZ``
    rotation, and uncomputation.  It supports arbitrary Pauli-string weight,
    including the higher-order strings generated by native HUBO BF-DCQO.
    """
    active = [qubit for qubit, pauli in enumerate(pauli_string) if pauli != "I"]
    if not active or abs(theta) < 1e-16:
        return []

    operations: list[tuple[str, int] | tuple[str, int, float]] = []
    for qubit in active:
        pauli = pauli_string[qubit]
        if pauli == "X":
            operations.append(("H", qubit))
        elif pauli == "Y":
            operations.append(("RX", qubit, math.pi / 2.0))
        elif pauli != "Z":
            raise ValueError(f"unsupported Pauli {pauli}")

    target = active[-1]
    for qubit in active[:-1]:
        operations.append(("CNOT", qubit, target))
    operations.append(("RZ", target, 2.0 * float(theta)))
    for qubit in reversed(active[:-1]):
        operations.append(("CNOT", qubit, target))

    for qubit in reversed(active):
        pauli = pauli_string[qubit]
        if pauli == "X":
            operations.append(("H", qubit))
        elif pauli == "Y":
            operations.append(("RX", qubit, -math.pi / 2.0))
    return operations


def pauli_rotation_resources(pauli_string) -> dict[str, int]:
    """Return logical gate counts for the generic Pauli-rotation decomposition."""
    weight = sum(pauli != "I" for pauli in pauli_string)
    basis_changes = sum(pauli in {"X", "Y"} for pauli in pauli_string)
    return {
        "weight": weight,
        "cnot": 0 if weight == 0 else 2 * max(weight - 1, 0),
        "rz": 0 if weight == 0 else 1,
        "basis_change_gates": 2 * basis_changes,
    }


def append_pauli_rotation(circuit, pauli_string, theta: float):
    """Append a generic Pauli-string rotation to a PyQPanda3 circuit."""
    _, _, _, H, RX, _, RZ, CNOT, _ = _import_qpanda()
    for operation in pauli_rotation_recipe(pauli_string, theta):
        name = operation[0]
        if name == "H":
            circuit << H(operation[1])
        elif name == "RX":
            circuit << RX(operation[1], operation[2])
        elif name == "RZ":
            circuit << RZ(operation[1], operation[2])
        elif name == "CNOT":
            circuit << CNOT(operation[1], operation[2])
        else:
            raise RuntimeError(f"unknown recipe operation {operation}")
    return circuit


def run_bfdcqo_probabilities(
    n: int,
    ry_angles: np.ndarray,
    trotter_layers,
) -> np.ndarray:
    """Run a BF-DCQO circuit on CPUQVM and return ideal probabilities."""
    QCircuit, QProg, CPUQVM, _, _, RY, _, _, _ = _import_qpanda()
    circuit = QCircuit()
    for qubit, angle in enumerate(ry_angles):
        circuit << RY(qubit, float(angle))
    for layer in trotter_layers:
        for pauli_string, theta in layer:
            append_pauli_rotation(circuit, pauli_string, theta)

    program = QProg(n)
    program.append(circuit)
    machine = CPUQVM()
    machine.run(program, 1)
    probability_dict = machine.result().get_prob_dict()
    prob = np.zeros(1 << n, dtype=float)
    for bits, value in probability_dict.items():
        prob[int(str(bits).replace(" ", ""), 2)] = float(value)
    return prob / prob.sum()


def build_qaoa_program(
    problem,
    betas: np.ndarray,
    gammas: np.ndarray,
    measure_all: bool,
):
    """Build a quadratic-Ising QAOA program for PyQPanda3 CPUQVM."""
    if not hasattr(problem, "h") or not hasattr(problem, "J"):
        raise TypeError(
            "QAOA baseline supports quadratic Ising/QUBO only; "
            "quadratize a HUBO before QAOA."
        )
    QCircuit, QProg, _, H, RX, _, RZ, CNOT, measure = _import_qpanda()
    n = problem.n
    circuit = QCircuit()
    for qubit in range(n):
        circuit << H(qubit)

    for beta, gamma in zip(betas, gammas):
        for i, field in enumerate(problem.h):
            if abs(field) > 1e-15:
                circuit << RZ(i, 2.0 * float(gamma * field))
        for i in range(n):
            for j in range(i + 1, n):
                coupling = problem.J[i, j]
                if abs(coupling) > 1e-15:
                    circuit << CNOT(i, j)
                    circuit << RZ(j, 2.0 * float(gamma * coupling))
                    circuit << CNOT(i, j)
        for qubit in range(n):
            circuit << RX(qubit, 2.0 * float(beta))

    program = QProg(n)
    program.append(circuit)
    if measure_all:
        program.append(measure(list(range(n)), list(range(n))))
    return program


def qaoa_probabilities(
    problem,
    betas: np.ndarray,
    gammas: np.ndarray,
) -> np.ndarray:
    """Return ideal QAOA probabilities from PyQPanda3 CPUQVM."""
    _, _, CPUQVM, *_ = _import_qpanda()
    program = build_qaoa_program(problem, betas, gammas, measure_all=False)
    machine = CPUQVM()
    machine.run(program, 1)
    probability_dict = machine.result().get_prob_dict()
    prob = np.zeros(1 << problem.n, dtype=float)
    for bits, value in probability_dict.items():
        prob[int(str(bits).replace(" ", ""), 2)] = float(value)
    return prob / prob.sum()


def qaoa_sample_counts(
    problem,
    betas: np.ndarray,
    gammas: np.ndarray,
    shots: int,
) -> dict[str, int]:
    """Sample a measured QAOA circuit with PyQPanda3 CPUQVM."""
    _, _, CPUQVM, *_ = _import_qpanda()
    program = build_qaoa_program(problem, betas, gammas, measure_all=True)
    machine = CPUQVM()
    machine.run(program, int(shots))
    return {
        str(bits).replace(" ", ""): int(count)
        for bits, count in machine.result().get_counts().items()
    }
